#!/usr/bin/env python3
# Generator: Swift VnLexi enum + tables from /tmp/unikey_dump.json + vnlexi.h parsing
import json, re

d = json.load(open('/tmp/unikey_dump.json'))

# ---- parse vnlexi.h enums ----
def parse_enum(path, name):
    src = open(path).read()
    m = re.search(r'enum\s+' + name + r'\s*\{(.*?)\};', src, re.S)
    body = m.group(1)
    items = []
    for line in body.split('\n'):
        line = re.sub(r'//.*', '', line).strip()
        for tok in line.split(','):
            tok = tok.strip()
            if not tok:
                continue
            if '=' in tok:
                tok = tok.split('=')[0].strip()
            items.append(tok)
    return items

lexi_names = parse_enum('/tmp/f5ukey/unikey/vnlexi.h', 'VnLexiName')
vseq_names = parse_enum('/tmp/f5ukey/unikey/vnlexi.h', 'VowelSeq')
cseq_names = parse_enum('/tmp/f5ukey/unikey/vnlexi.h', 'ConSeq')

# vnl_nonVnChar = -1 explicitly, then sequential; vnl_lastChar keeps value
lexi_values = []
val = 0
for i, n in enumerate(lexi_names):
    if n == 'vnl_nonVnChar':
        lexi_values.append(-1)
        val = 0
    else:
        lexi_values.append(val)
        val += 1
assert lexi_names[0] == 'vnl_nonVnChar'

vseq_values = {}
v = 0
for i, n in enumerate(vseq_names):
    if n == 'vs_nil':
        vseq_values[n] = -1
    else:
        vseq_values[n] = v
        v += 1
assert len(vseq_names) == 71, len(vseq_names)

cseq_values = {}
v = 0
for i, n in enumerate(cseq_names):
    if n == 'cs_nil':
        cseq_values[n] = -1
    else:
        cseq_values[n] = v
        v += 1
assert len(cseq_names) == 31, len(cseq_names)

# ---- validate dump rows align with enums ----
assert len(d['vseq']) == 70 and len(d['cseq']) == 30
# row i must match vseq name i-1?? careful: first row corresponds to vs_a (name index 1)
for i, row in enumerate(d['vseq']):
    name = vseq_names[i + 1]
    assert vseq_values[name] == i, (name, i)
# last vseq row value must equal vseq_names last
assert vseq_values[vseq_names[-1]] == len(d['vseq']) - 1
for i, row in enumerate(d['cseq']):
    name = cseq_names[i + 1]
    assert cseq_values[name] == i, (name, i)
assert cseq_values[cseq_names[-1]] == len(d['cseq']) - 1

# ---- vowel classification ----
vowels = set()
for idx, n in enumerate(lexi_names):
    if n in ('vnl_nonVnChar',):
        continue
    base = n[4:]  # after 'vnl_'
    if base in ('dd', 'DD'):
        continue
    c = base[0].lower()
    if c in 'aeiouy':
        vowels.add(idx)
    elif len(base) == 2 and base[1] in '12345r' and base[0].lower() in 'aeiouy':
        vowels.add(idx)

# ---- emit Swift ----
w = []
w.append('// GENERATED by scripts/gen_tables.py from UniKey engine (fcitx5-unikey, LGPL-2.0+).')
w.append('// Do not edit by hand. Engine data: vowel sequences, consonant sequences, char tables.')
w.append('')
w.append('/// Lexical Vietnamese units (mirrors UniKey VnLexiName). Case bit: even = uppercase.')
w.append('enum VnLexi: Int {')
for i, n in enumerate(lexi_names):
    w.append('    case %s = %s' % (n, lexi_values[i]))
w.append('}')
w.append('')
w.append('/// Vowel sequence identifiers (mirrors UniKey VowelSeq).')
w.append('enum VnVowelSeq: Int {')
for i, n in enumerate(vseq_names):
    w.append('    case %s = %s' % (n, vseq_values[n]))
w.append('}')
w.append('')
w.append('/// Consonant sequence identifiers (mirrors UniKey ConSeq).')
w.append('enum VnConSeq: Int {')
for i, n in enumerate(cseq_names):
    w.append('    case %s = %d' % (n, cseq_values[n]))
w.append('}')
w.append('')

# VSeqList rows
COLS = '//                        len complete conSuf v0   v1   v2   sub0 sub1 sub2 roofPos withRoof hookPos withHook'
w.append('/// Vowel-sequence table. Columns:')
w.append('/// 0 len, 1 complete, 2 conSuffix, 3..5 v[], 6..8 sub[], 9 roofPos, 10 withRoof, 11 hookPos, 12 withHook')
w.append('enum VnTables {')
w.append('static let noop = 0')
w.append('static let vSeqList: [[Int]] = [')
for i, row in enumerate(d['vseq']):
    name = vseq_names[i + 1]
    flat = [row['len'], row['complete'], row['conSuffix']] + row['v'] + row['sub'] + [row['roofPos'], row['withRoof'], row['hookPos'], row['withHook']]
    w.append('    [%s],  // %s' % (', '.join('%4d' % x for x in flat), name))
w.append(']')
w.append('')
w.append('/// Consonant-sequence table. Columns: 0 len, 1..3 c[], 4 suffix-allowed')
w.append('static let cSeqList: [[Int]] = [')
for i, row in enumerate(d['cseq']):
    name = cseq_names[i + 1]
    flat = [row['len']] + row['c'] + [row['suffix']]
    w.append('    [%s],  // %s' % (', '.join('%4d' % x for x in flat), name))
w.append(']')
w.append('')
w.append('/// Valid (vowelSeq, consonantSuffix) pairs for spell checking.')
w.append('static let vcPairs: [[Int]] = [')
for p in d['vcPairs']:
    w.append('    [%d, %d],' % (p[0], p[1]))
w.append(']')
w.append('')
w.append('/// UniKey standard charset: index = VnLexi raw value (+), value = Unicode scalar.')
w.append('static let lexiUnicode: [Int] = [')
line = ''
for i, cp in enumerate(d['unicodeTable']):
    line += ('%d, ' % cp)
    if len(line) > 100:
        w.append('    ' + line)
        line = ''
if line:
    w.append('    ' + line)
w.append(']')
w.append('')
w.append('/// For each lexeme, its tone-less canonical version.')
w.append('static let lexiNoTone: [Int] = [' )
line = ''
for i, cp in enumerate(d['stdVnNoTone']):
    line += ('%d, ' % cp)
    if len(line) > 100:
        w.append('    ' + line)
        line = ''
if line:
    w.append('    ' + line)
w.append(']')
w.append('')
w.append('/// For each lexeme, its base letter version (roof/bowl/hook removed).')
w.append('static let lexiRootChar: [Int] = [')
line = ''
for i, cp in enumerate(d['stdVnRootChar']):
    line += ('%d, ' % cp)
    if len(line) > 100:
        w.append('    ' + line)
        line = ''
if line:
    w.append('    ' + line)
w.append(']')
w.append('}')

out = '\n'.join(w) + '\n'
import os
os.makedirs('/Volumes/khoilm9_ssd/MiniUnikey/Sources/MiniUnikey/Engine', exist_ok=True)
open('/Volumes/khoilm9_ssd/MiniUnikey/Sources/MiniUnikey/Engine/VniTables.swift', 'w').write(out)
print('vowels:', len(vowels), 'vseq:', len(vseq_names), 'lexi:', len(lexi_names))
print('written VniTables.swift')
